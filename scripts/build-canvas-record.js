#!/usr/bin/env node
'use strict';

/**
 * Inline scripts/lib/canvas-record-block.js into the week renderer, between its
 * sentinels.
 *
 *   node scripts/build-canvas-record.js            write it
 *   node scripts/build-canvas-record.js --check    fail on drift, write nothing
 *
 * The record grammar has exactly one implementation. The week renderer is a
 * browser file that nothing generates, so it gets the block by inlining rather
 * than by being rebuilt; the generated briefs get the same block from
 * scripts/lib/brief-capture-block.js. `--check` is what validate.js runs, so a
 * hand-edit between the sentinels fails the push instead of quietly becoming a
 * second answer to "did this student edit their work".
 *
 * Never hand-edit between the sentinels. Change the lib and run this.
 */

const fs = require('fs');
const path = require('path');
const { recordBlockSource } = require('./lib/canvas-record-block');

const ROOT = path.resolve(__dirname, '..');
const TARGET = path.join(ROOT, 'assets', 'js', 'becurrent-week-renderer-v1.js');

const BEGIN = '// BEGIN INLINED CANVAS RECORD BLOCK, generated by scripts/build-canvas-record.js';
const END = '// END INLINED CANVAS RECORD BLOCK';

const check = process.argv.includes('--check');

const src = fs.readFileSync(TARGET, 'utf8');
const start = src.indexOf(BEGIN);
const stop = src.indexOf(END);

if (start === -1 || stop === -1 || stop < start) {
  console.error(`FAIL ${path.relative(ROOT, TARGET)}: the inline sentinels are missing.\n`
    + `      Expected:\n        ${BEGIN}\n        ...\n        ${END}`);
  process.exit(1);
}

const wanted = BEGIN + '\n' + recordBlockSource('') + '\n' + END;
const found = src.slice(start, stop + END.length);

if (found === wanted) {
  console.log(`OK   ${path.relative(ROOT, TARGET)} carries the current record block`);
  process.exit(0);
}

if (check) {
  console.error(`FAIL ${path.relative(ROOT, TARGET)}: the inlined record block has drifted from\n`
    + '      scripts/lib/canvas-record-block.js. Run: node scripts/build-canvas-record.js');
  process.exit(1);
}

fs.writeFileSync(TARGET, src.slice(0, start) + wanted + src.slice(stop + END.length));
console.log(`WROTE ${path.relative(ROOT, TARGET)}, record block refreshed`);
