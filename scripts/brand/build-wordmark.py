#!/usr/bin/env python3
"""Derive every BeCurrent lockup from the supplied logo artwork.

Writes assets/images/brand/*.svg, the Canvas PNGs and assets/favicon.svg. Run
from the repo root:

    pip install pillow numpy potracer
    python3 -I scripts/brand/build-wordmark.py

── The source of truth ─────────────────────────────────────────────────────────

assets/images/brand/source/ holds the artwork as it was supplied on 2026-10-20,
five raster files, unedited:

  becurrent-wordmark-source.png        the word in ink with the red full stop
  becurrent-wordmark-paper-source.webp the same word in paper, for dark grounds
  becurrent-logo-source.webp           the word over the CURRENT EVENTS tagline
  becurrent-brief-source.png           the word over a red rule and THE BRIEF
  becurrent-monogram-source.webp       BC. in paper on a black square

Everything else in the brand folder is derived from them by this script, which
does three things and only three: trace, trim and recolour. It never redraws.
The tracing is potrace, so the outputs are the artwork's own outlines as vector
paths, which is what lets one file stay sharp from a 16px browser tab to a
projector.

**Do not hand-edit the outputs.** Replace a source or edit this script.

── Why the colours are set here rather than sampled ────────────────────────────

The five files were drawn separately and their reds disagree: the full stop
samples anywhere from #D00800 to #E41404 across them. Sampling each would give
the course five reds. So every red is the one token, --signal #CE1400, which is
the red the site already uses and within a few points of the main wordmark's own
dot. The ink is --black-900 #111111 and the paper is --clean-paper #FFFEFB.

── The outputs ─────────────────────────────────────────────────────────────────

  becurrent-wordmark-ink.svg   word in ink, for light grounds (the default now)
  becurrent-wordmark.svg       word in paper, for dark bands
  becurrent-logo-ink.svg       word and tagline in ink, no plate
  becurrent-logo.svg           word and tagline on a black plate. It carries its
                               own ground because the older investigation pages
                               put it on dark mastheads, and a plate looks right
                               on any ground.
  becurrent-brief.svg          the BeCurrent / THE BRIEF lockup
  becurrent-monogram.svg       BC. on its square
  favicon.svg                  the monogram at 64x64, in assets/
  becurrent-wordmark-ink.png   for Canvas, which cannot be trusted with SVG in
                               every client (the mobile app, notification email)

The paper wordmark is the ink wordmark's own geometry recoloured, not a trace of
the paper source. Two traces of two drawings would be two slightly different
logos, and the only difference between the colourways must be the fill.

── The legibility floor ────────────────────────────────────────────────────────

The new word is wide and heavy, about 6.8:1, and its cap height is most of the
mark's height. That is the opposite of the old C lockup, whose word was a third
of its height: this one is readable at a 24px masthead. Measure again if the
artwork changes.

Deliberately off the test path: this needs three pip packages and validate.js has
to stay runnable on a bare checkout. The outputs are committed, so nothing in the
build or the gate depends on this file.
"""
import os

import numpy as np
import potrace
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
BRAND = os.path.join(ROOT, 'assets', 'images', 'brand')
SRC = os.path.join(BRAND, 'source')

INK = '#111111'      # --black-900
RED = '#CE1400'      # --signal
PAPER = '#FFFEFB'    # --clean-paper
PLATE = '#111111'
CANVAS_PNG_WIDTH = 480   # rendered at 240 CSS px in Canvas, so sharp at 2x

HEAD = ('<!-- Generated by scripts/brand/build-wordmark.py from the supplied artwork in\n'
        '     assets/images/brand/source/. Traced, trimmed and recoloured, never\n'
        '     redrawn. Do not hand-edit; replace the source or edit the script.\n'
        '     Width and height are explicit, per the image contract in CLAUDE.md. -->\n')


def load(name):
    im = Image.open(os.path.join(SRC, name)).convert('RGBA')
    return np.asarray(im).astype(np.int32)


def masks(px):
    """Split the artwork into the three things it is drawn in. The grounds are
    transparent, so alpha decides what is artwork at all; colour decides which
    of ink, red or paper it is."""
    r, g, b, a = px[..., 0], px[..., 1], px[..., 2], px[..., 3]
    solid = a >= 128
    red = solid & (r > 140) & (g < 90) & (b < 90)
    lum = 0.299 * r + 0.587 * g + 0.114 * b
    ink = solid & ~red & (lum < 128)
    paper = solid & ~red & (lum >= 128)
    return ink, red, paper


def trace(mask):
    """Potrace a boolean mask into one SVG path string, in pixel units."""
    if not mask.any():
        return ''
    # potracer traces the False pixels, the opposite of what the name suggests.
    path = potrace.Bitmap(~mask).trace(turdsize=8, alphamax=1.0, opticurve=True,
                                      opttolerance=0.2)
    out = []
    for curve in path:
        s = curve.start_point
        out.append(f'M{s.x:.1f} {s.y:.1f}')
        for seg in curve.segments:
            if seg.is_corner:
                out.append(f'L{seg.c.x:.1f} {seg.c.y:.1f}L{seg.end_point.x:.1f} {seg.end_point.y:.1f}')
            else:
                out.append(f'C{seg.c1.x:.1f} {seg.c1.y:.1f} {seg.c2.x:.1f} {seg.c2.y:.1f} '
                           f'{seg.end_point.x:.1f} {seg.end_point.y:.1f}')
        out.append('Z')
    return ''.join(out)


def bounds(*ms):
    m = np.zeros_like(ms[0])
    for x in ms:
        m = m | x
    ys, xs = np.nonzero(m)
    return int(xs.min()), int(ys.min()), int(xs.max()) + 1, int(ys.max()) + 1


def svg(box, layers, label, w=None, h=None, pad=0, ground=None, square=False):
    x0, y0, x1, y1 = box
    x0, y0, x1, y1 = x0 - pad, y0 - pad, x1 + pad, y1 + pad
    if square:
        # Grow the short side about the centre, so the ground is a true square.
        side = max(x1 - x0, y1 - y0)
        cx, cy = (x0 + x1) / 2, (y0 + y1) / 2
        x0, y0 = round(cx - side / 2), round(cy - side / 2)
        x1, y1 = x0 + side, y0 + side
    vw, vh = x1 - x0, y1 - y0
    w = w or vw
    h = h or vh
    body = ''
    if ground:
        body += f'<rect x="{x0}" y="{y0}" width="{vw}" height="{vh}" fill="{ground}"/>'
    for d, fill in layers:
        if d:
            body += f'<path fill="{fill}" fill-rule="evenodd" d="{d}"/>'
    return (f'{HEAD}<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="{h}" '
            f'viewBox="{x0} {y0} {vw} {vh}" role="img" aria-label="{label}">'
            f'<title>{label}</title>{body}</svg>\n')


def write(rel, text, mode='w'):
    path = os.path.join(ROOT, rel)
    with open(path, mode) as fh:
        fh.write(text)
    print(f'  {rel}  {len(text)} bytes')


B = 'assets/images/brand/'

# ── The wordmark, both colourways, one geometry ──────────────────────────────
px = load('becurrent-wordmark-source.png')
ink, red, _ = masks(px)
box = bounds(ink, red)
word, dot = trace(ink), trace(red)
write(B + 'becurrent-wordmark-ink.svg', svg(box, [(word, INK), (dot, RED)], 'BeCurrent'))
write(B + 'becurrent-wordmark.svg', svg(box, [(word, PAPER), (dot, RED)], 'BeCurrent'))

# The Canvas PNG comes off the same source pixels, recoloured to the tokens and
# keeping the source's own antialiased alpha, then trimmed and resized.
x0, y0, x1, y1 = box
crop = px[y0:y1, x0:x1].copy()
rr = masks(crop)[1] | ((crop[..., 0] > 140) & (crop[..., 1] < 90) & (crop[..., 2] < 90))
crop[..., 0:3] = np.where(rr[..., None], [0xCE, 0x14, 0x00], [0x11, 0x11, 0x11])
png = Image.fromarray(crop.astype(np.uint8), 'RGBA')
png = png.resize((CANVAS_PNG_WIDTH, round(CANVAS_PNG_WIDTH * (y1 - y0) / (x1 - x0))),
                 Image.LANCZOS)
png.save(os.path.join(ROOT, B + 'becurrent-wordmark-ink.png'), optimize=True)
print(f'  {B}becurrent-wordmark-ink.png  {png.size[0]}x{png.size[1]}')

# ── The logo with its tagline ────────────────────────────────────────────────
px = load('becurrent-logo-source.webp')
ink, red, _ = masks(px)
box = bounds(ink, red)
word, dot = trace(ink), trace(red)
write(B + 'becurrent-logo-ink.svg', svg(box, [(word, INK), (dot, RED)], 'BeCurrent, Current Events'))
pad = round((box[3] - box[1]) * 0.22)
write(B + 'becurrent-logo.svg', svg(box, [(word, PAPER), (dot, RED)], 'BeCurrent, Current Events',
                                     pad=pad, ground=PLATE))

# ── The Brief lockup ─────────────────────────────────────────────────────────
px = load('becurrent-brief-source.png')
ink, red, _ = masks(px)
write(B + 'becurrent-brief.svg', svg(bounds(ink, red), [(trace(ink), INK), (trace(red), RED)],
                                     'BeCurrent, The Brief'))

# ── The monogram and the favicon ─────────────────────────────────────────────
# The square is drawn as a rectangle rather than traced with the letters as holes
# in it, so no antialiased seam can open up between the square and the letters
# laid over it. The supplied square is 898x858, a few percent off true; it is
# made square about its own centre, because a browser tab and an app icon are
# square and a near-square letterboxes in both.
px = load('becurrent-monogram-source.webp')
ink, red, paper = masks(px)
sq = bounds(ink)
letters, dot = trace(paper), trace(red)
write(B + 'becurrent-monogram.svg', svg(sq, [(letters, PAPER), (dot, RED)], 'BeCurrent', ground=PLATE,
                                         square=True))
write('assets/favicon.svg', svg(sq, [(letters, PAPER), (dot, RED)], 'BeCurrent', w=64, h=64,
                                ground=PLATE, square=True))
