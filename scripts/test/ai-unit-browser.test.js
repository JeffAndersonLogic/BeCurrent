#!/usr/bin/env node
'use strict';
const assert=require('assert');
const {open}=require('./midterms-browser-helper');
const CORE=require('../lib/canvas-parse-core');
const unit=require('../lib/unit-content/ai');
const calendar=require('../lib/semester-calendar');
(async()=>{
 const {browser,server,root}=await open();
 const context=await browser.newContext({viewport:{width:1365,height:900}});
 await context.route('https://jeffandersonlogic.github.io/BeCurrent/assets/images/brand/becurrent-wordmark-ink.png',route=>route.fulfill({path:require('path').join(__dirname,'../../assets/images/brand/becurrent-wordmark-ink.png'),contentType:'image/png'}));
 const page=await context.newPage(),errors=[];
 await page.clock.install({time:new Date('2026-11-17T15:00:00Z')});
 page.setDefaultTimeout(8000);
 page.on('pageerror',e=>errors.push(e.message));
 await page.addInitScript(()=>{Object.defineProperty(navigator,'clipboard',{configurable:true,value:{write:async items=>{window.__copiedHtml=await(await items[0].getType('text/html')).text()}}})});
 try{
  await page.goto(root+'/ai/opening-film.html');
  assert(await page.isVisible('h1'));
  assert.match(await page.textContent('main'),/A\.I\. Revolution/);
  assert.match(await page.textContent('main'),/53:30/);
  assert.match(await page.textContent('main'),/CNN10/);
  assert.match(await page.textContent('main'),/No homework/i);
  assert.strictEqual(await page.locator('[data-slot],#gather-work').count(),0,'film day has no written work');
  assert((await page.locator('a[href*="-sB12gk9ESA"]').count())>=1,'full official NOVA film linked');
  await page.goto(root+'/ai/block-02.html');
  assert(await page.isVisible('#student-flow'),'AI2 lesson loads');
  assert((await page.textContent('main')).includes('What Exactly AI Is'));
  assert.strictEqual(await page.locator('[data-slot]').count(),8);
  assert.strictEqual(await page.locator('[data-sort]').count(),8);
  assert.strictEqual(await page.locator('[data-student-chapter]').count(),5);
  await page.fill('#ai-q1','A learned model uses examples while a calculator follows fixed rules.');
  await page.reload();
  assert((await page.inputValue('#ai-q1')).includes('basic')||(await page.inputValue('#ai-q1')).includes('calculator'),'autosave survives reload');
  for(let i=0;i<unit.topics[0].sort.items.length;i++)await page.selectOption('#sort-'+(i+1),unit.topics[0].sort.items[i][1]);
  await page.click('#check-sort');
  assert((await page.textContent('#sort-feedback')).includes('8 of 8 correct'),'sort has feedback');
  for(let k=1;k<=8;k++)await page.fill('#ai-q'+k,'AI2 question '+k+' evidence-based answer.');
  await page.click('#gather-work');
  await page.waitForFunction(()=>document.getElementById('copy-preview').value.includes('#BHV|'));
  const plain=await page.inputValue('#copy-preview');
  const parsed=CORE.parseSubmission(plain,'test_student_text.txt');
  assert.strictEqual(parsed.hasManifest,true);
  assert.strictEqual(parsed.responses.length,9,'eight responses plus classification');
  assert.deepStrictEqual(parsed.exceptions,[]);
  assert(plain.includes('topic=ai-t02'));
  await page.fill('#ai-q1','Revised after gathering');
  assert.strictEqual(await page.getAttribute('#copy-preview','data-stale'),'true');
  await page.click('#select-work');
  const fresh=CORE.parseSubmission(await page.inputValue('#copy-preview'),'test_student_text.txt');
  assert.deepStrictEqual(fresh.exceptions,[]);
  assert((await page.inputValue('#copy-preview')).includes('Revised after gathering'));
  await page.setViewportSize({width:390,height:844});
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+2),'AI2 responsive mobile layout');
  await page.goto(root+'/ai/print-topic-02.html');
  assert.strictEqual(await page.locator('article').count(),8,'AI2 print fallback');
  for(let n=3;n<=5;n++){
   await page.goto(root+'/ai/block-0'+n+'.html');
   assert.strictEqual(await page.locator('[data-slot]').count(),8,'AI'+n+' has eight answers');
   assert(await page.isVisible('#gather-work'));
  }
  await page.goto(root+'/docs/canvas/ai-unit-calendar.html');
  const events=calendar.events;
  const count=events.length+events.filter(e=>e.kind!=='video').length+events.filter(e=>e.also).length;
  assert.strictEqual(await page.locator('[data-copy]').count(),count,'Canvas event and assignment count');
  for(const html of await page.locator('textarea').evaluateAll(els=>els.map(e=>e.value)))assert.match(html,/becurrent-wordmark-ink\.png/,'all Canvas HTML carries brand');
  await page.evaluate(()=>Object.defineProperty(navigator,'clipboard',{configurable:true,value:{writeText:async text=>{window.__copiedCode=text}}}));
  await page.locator('#day-2026-11-17 summary').click();
  await page.locator('[data-copy="event-3"]').click();
  const copied=await page.evaluate(()=>window.__copiedCode);
  assert.match(copied,/-sB12gk9ESA/);
  assert.match(copied,/No homework/);
  assert(!copied.includes('&lt;h2&gt;'),'copy produces real HTML, not escaped preview');
  assert.strictEqual(await page.locator('#day-2026-11-17 [data-copy]').count(),1,'film day has calendar event but no assignment');
  await page.goto(root+'/announcements.html?date=2026-11-17');
  assert.strictEqual(await page.textContent('.title-topic'),'AI1 - Intro to AI (Nova Video)');
  assert.strictEqual(await page.locator('.lead-slide').count(),1,'NOVA board must include an actual lead headline slide');
  assert.match(await page.textContent('.lead-headline'),/California sues OpenAI over alleged AI safety failures/);
  assert.match(await page.textContent('.lead-dek'),/OpenAI says/);
  assert.strictEqual(await page.locator('.lead-link').getAttribute('href'),'https://apnews.com/article/1dd7be56134b4f09fb2fb974803edc69');
  assert.doesNotMatch(await page.locator('#stage').innerText(),/CE - |60 Minutes Interview with President Trump/);
  assert.strictEqual(await page.locator('.desk-slide-v2').count(),0,'no Desk submission on film day');
  assert((await page.locator('a[href*="-sB12gk9ESA"]').count())>=1,'board links NOVA');
  await page.goto(root+'/index.html');
  assert.match(await page.textContent('[data-class-announcement]'),/AI1 - Intro to AI \(Nova Video\)/);
  assert.deepStrictEqual(errors,[]);
  console.log('PASS: NOVA video AI1/no homework, AI2–AI5 autosave and Canvas roundtrip, AI6 calendar, website announcement and branded HTML.');
 }finally{await context.close();await browser.close();server.close()}
})().catch(e=>{console.error(e.stack||e);process.exit(1)});
