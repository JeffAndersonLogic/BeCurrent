#!/usr/bin/env node
'use strict';
/**
 * Projector data is generated from the teacher lesson, intentionally stripping
 * the Teacher Intelligence cues before they reach the presentation window.
 *
 * node scripts/build-control-room.js
 * node scripts/build-control-room.js --check
 */
const fs=require('fs');
const path=require('path');
const ROOT=path.resolve(__dirname,'..');
const lesson=require('../teacher/data/midterms-block-01');
const file=path.join(ROOT,'teacher/data/midterms-block-01-projector.js');
const project={
  key:lesson.key,unit:lesson.unit,title:lesson.title,
  question:lesson.question,totalMinutes:lesson.totalMinutes,
  storageKey:lesson.storageKey,
  phases:lesson.phases.map(p=>({
    id:p.id,label:p.label,kind:p.kind,time:p.time,
    start:p.start,minutes:p.minutes,screen:p.screen
  }))
};
const expected='/* GENERATED by scripts/build-control-room.js. Student-safe presentation data. */\n'
  +'window.BECURRENT_PROJECTOR_LESSON = '+JSON.stringify(project,null,2)+';\n';
if(process.argv.includes('--check')){
  if(!fs.existsSync(file)||fs.readFileSync(file,'utf8')!==expected){
    console.error('FAIL: Midterms projector data has drifted. Run node scripts/build-control-room.js');
    process.exit(1);
  }
  console.log('PASS: projector data reproduces and contains no teacher-intelligence fields');
}else{
  if(!fs.existsSync(file)||fs.readFileSync(file,'utf8')!==expected){
    fs.writeFileSync(file,expected);
    console.log('Wrote teacher/data/midterms-block-01-projector.js');
  }else console.log('Projector data is already current');
}
module.exports={project,expected};
