#!/usr/bin/env node
'use strict';

/**
 * Write teacher/teaching-os-manifest.js: for every topic code the schedule can
 * name, where its teacher cockpit, projector and student page are.
 *
 *   node scripts/build-teaching-os-manifest.js            write
 *   node scripts/build-teaching-os-manifest.js --check    fail on drift, write nothing
 *
 * The reader is the JeffOS Teaching Command Center (AndersonLogic-OS,
 * 00_START_HERE/Teaching-Command-Center/), which loads this file live from
 * GitHub Pages the same way it loads BeHistorical's run-of-show-manifest.js.
 * Without it the Command Center could only guess at BeCurrent URLs, so it knew
 * the Iran days and sent every other day to the teacher hub.
 *
 * It is generated from the unit content modules and the shared page names in
 * scripts/lib/teacher-paths.js, never typed, and it refuses to write when:
 *   - an entry points at a file that does not exist, or
 *   - a topic code in assets/data/announcements-schedule.js has no entry,
 * because either one is a Command Center button that opens nothing on the day
 * it is needed.
 */

const fs = require('fs');
const path = require('path');
const { teachingTopics } = require('./lib/teaching-os');

const ROOT = path.resolve(__dirname, '..');
const CHECK = process.argv.includes('--check');
const OUT = path.join('teacher', 'teaching-os-manifest.js');
const R = '\x1b[31m', G = '\x1b[32m', X = '\x1b[0m';

const topics = teachingTopics();

const problems = [];
const seen = new Set();
topics.forEach(e => {
  if (seen.has(e.code)) problems.push(`${e.code} is listed twice`);
  seen.add(e.code);
  ['student', 'teacher', 'projector', 'hub', 'unitPage'].forEach(k => {
    if (!e[k]) return;
    const file = e[k].split('?')[0];
    if (!fs.existsSync(path.join(ROOT, file))) problems.push(`${e.code} ${k} points at ${file}, which does not exist`);
  });
});

// Every scheduled code must resolve, or that day's buttons route nowhere.
global.window = {};
require(path.join(ROOT, 'assets', 'data', 'announcements-schedule.js'));
(((global.window.BECURRENT_SCHEDULE || {}).days) || []).forEach(d => {
  if (d && d.topic && !seen.has(d.topic)) problems.push(`the schedule names ${d.topic} on ${d.date}, which no unit defines`);
});

if (problems.length) {
  console.error(`\n${R}The Teaching OS manifest was not written:${X}`);
  problems.forEach(p => console.error(`  ${R}✗${X} ${p}`));
  process.exit(1);
}

const content = '/* GENERATED by scripts/build-teaching-os-manifest.js. Do not hand-edit.\n'
  + '   Read live by the JeffOS Teaching Command Center. Paths are relative to the site root. */\n'
  + 'window.BECURRENT_TEACHING_OS=' + JSON.stringify({
    generatedFrom: 'scripts/lib/unit-content + scripts/lib/teacher-paths.js',
    topics
  }) + ';\n';

const full = path.join(ROOT, OUT);
const existing = fs.existsSync(full) ? fs.readFileSync(full, 'utf8') : null;
if (CHECK) {
  if (existing === content) {
    console.log(`${G}✓${X} The Teaching OS manifest reproduces (${topics.length} topic codes).`);
    process.exit(0);
  }
  console.error(`\n${R}${OUT} has drifted. Run: node scripts/build-teaching-os-manifest.js${X}\n`);
  process.exit(1);
}
if (existing === content) console.log(`${G}✓${X} Already up to date.`);
else { fs.writeFileSync(full, content, 'utf8'); console.log(`  wrote ${OUT} (${topics.length} topic codes)`); }
