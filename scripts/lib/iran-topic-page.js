'use strict';

const { recordBlockSource } = require('./canvas-record-block');

/**
 * Browser layer for the Reverse History renderer.
 *
 * The narrative HTML remains deliberately bespoke, but its topic identity,
 * targets, criteria, filing prompts, progress, and Canvas record all come from
 * scripts/lib/unit-content/iran.js. This is the contract that keeps those pages
 * in the same course system as generated Briefs without flattening their design.
 */
function renderIranBrowser(unit) {
  const publicTopics = {};
  (unit.topics || []).forEach(t => {
    publicTopics[`topic-${String(t.n).padStart(2, '0')}`] = {
      n: t.n,
      key: t.key,
      title: t.title,
      subtitle: t.subtitle,
      page: t.page,
      overview: t.overview,
      learningTargets: t.learningTargets || [],
      successCriteria: t.successCriteria || [],
      questions: t.questions || []
    };
  });

  return `// GENERATED by scripts/build-iran.js from scripts/lib/unit-content/iran.js.
// The shared Canvas record grammar is inserted from canvas-record-block.js.
// Never hand-edit this file; edit the content module or this renderer and rebuild.
(()=>{
  'use strict';

  const UNIT=${JSON.stringify({
    unit: unit.meta.unit,
    course: unit.meta.course,
    reviewed: unit.meta.reviewed,
    terminalQuestion: unit.meta.terminalQuestion
  })};
  const TOPICS=${JSON.stringify(publicTopics)};
  const body=document.body;
  const topic=body.dataset.topic||'topic-01';
  const meta=TOPICS[topic];
  if(!meta)return;
  const prefix='bcv2-iran-'+topic+'-';
  const modeButtons=[...document.querySelectorAll('[data-mode]')];

  function esc(value){
    return String(value==null?'':value).replace(/&/g,'&amp;').replace(/</g,'&lt;')
      .replace(/>/g,'&gt;').replace(/"/g,'&quot;');
  }

  function installPosition(){
    if(document.querySelector('.ir-position'))return;
    const anchor=document.querySelector('.sticky-journey')||document.querySelector('.mast');
    if(!anchor)return;
    const bar=document.createElement('div');
    bar.className='ir-position';
    bar.innerHTML='<div class="ir-position-inner"><div><div class="ir-position-series">IRAN AT WAR · REVERSE HISTORY INVESTIGATION</div><div class="ir-position-title">Topic '+meta.n+' · '+esc(meta.title)+'</div><span class="ir-position-series">'+esc(meta.subtitle)+'</span></div><div class="ir-position-count"><strong>'+meta.n+'</strong> of 8 topics</div></div>';
    anchor.insertAdjacentElement('afterend',bar);
  }

  function installStudyGuide(){
    const nav=document.querySelector('.nav .nav-inner');
    if(!nav||nav.querySelector('a[href="study-guide.html"]'))return;
    const guide=document.createElement('a');
    guide.href='study-guide.html';
    guide.textContent='Study Guide';
    nav.appendChild(guide);
  }

  function installObjectives(){
    if(document.getElementById('objectives'))return;
    const hero=document.querySelector('.ir-hero');
    if(!hero)return;
    const section=document.createElement('section');
    section.className='ir-section ir-objectives';
    section.id='objectives';
    const targets=meta.learningTargets.map(t=>'<li><strong>'+esc(t.skill)+'.</strong> '+esc(t.target)+'</li>').join('');
    const criteria=meta.successCriteria.map(c=>'<li><strong>'+esc(c.skill)+'.</strong> '+esc(c.criteria)+'</li>').join('');
    section.innerHTML='<details><summary><span><span class="ir-kicker red">Today\\'s direction</span><strong>Learning targets and success criteria</strong></span><span aria-hidden="true">+</span></summary><div class="ir-objective-grid"><div><h2>Learning targets</h2><ol>'+targets+'</ol></div><div><h2>Success criteria</h2><ol>'+criteria+'</ol></div></div></details>';
    hero.insertAdjacentElement('afterend',section);
  }

  function setMode(mode){
    body.classList.toggle('teacher-on',mode==='teacher');
    modeButtons.forEach(b=>b.setAttribute('aria-pressed',String(b.dataset.mode===mode)));
    try{localStorage.setItem('bcv2-mode',mode)}catch(_){ }
  }
  let savedMode='student';
  try{savedMode=localStorage.getItem('bcv2-mode')||'student'}catch(_){ }
  modeButtons.forEach(b=>b.addEventListener('click',()=>setMode(b.dataset.mode)));
  setMode(savedMode);
  installPosition();
  installStudyGuide();
  installObjectives();

  const groups=[...document.querySelectorAll('[data-group]')];

  function read(key){
    try{
      const raw=localStorage.getItem(prefix+key);
      return raw===null?null:JSON.parse(raw);
    }catch(_){return null}
  }
  function write(key,value){
    try{localStorage.setItem(prefix+key,JSON.stringify(value));return true}catch(_){return false}
  }
  function valueOf(group){
    if(group.matches('textarea,input[type="text"],input[type="url"]'))return group.value;
    return [...group.querySelectorAll('input:checked')].map(i=>i.value);
  }
  function textValue(group){
    const value=valueOf(group);
    return Array.isArray(value)?value.join('; '):String(value||'');
  }
  function restore(group,value){
    if(value===null)return;
    if(group.matches('textarea,input[type="text"],input[type="url"]'))group.value=value||'';
    else if(Array.isArray(value))group.querySelectorAll('input').forEach(i=>i.checked=value.includes(i.value));
  }
  groups.forEach(g=>restore(g,read(g.dataset.group)));

  document.querySelectorAll('[data-max]').forEach(group=>{
    const max=Number(group.dataset.max)||0;
    if(!max)return;
    function paint(){
      const counter=group.parentElement.querySelector('[data-choice-count]');
      if(counter)counter.textContent=[...group.querySelectorAll('input:checked')].length+' of '+max+' selected';
    }
    group.addEventListener('change',event=>{
      if(!event.target.matches('input[type="checkbox"]'))return;
      if([...group.querySelectorAll('input:checked')].length>max)event.target.checked=false;
      paint();
    });
    paint();
  });

  function filled(key){
    const value=read(key);
    return Array.isArray(value)?value.length>0:typeof value==='string'&&value.trim().length>0;
  }
  function updateProgress(){
    const keys=meta.questions.map(q=>q.group);
    const done=keys.filter(filled).length;
    document.querySelectorAll('[data-topic-progress]').forEach(el=>el.textContent=done+' of '+keys.length+' saved');
  }

  // Save continuously so leaving the page after typing cannot strand the last
  // paragraph. The visible buttons remain as an explicit reassurance and status.
  groups.forEach(group=>{
    const eventName=group.matches('textarea,input[type="text"],input[type="url"]')?'input':'change';
    group.addEventListener(eventName,()=>{
      write(group.dataset.group,valueOf(group));
      updateProgress();
    });
  });

  document.querySelectorAll('[data-save]').forEach(btn=>btn.addEventListener('click',()=>{
    const key=btn.dataset.save;
    const group=document.querySelector('[data-group="'+key+'"]');
    if(!group)return;
    const ok=write(key,valueOf(group));
    const status=document.querySelector('[data-status="'+key+'"]');
    if(status){
      status.textContent=ok?'Saved on this Chromebook':'Could not save in this browser';
      if(ok)setTimeout(()=>{status.textContent=''},2400);
    }
    updateProgress();
  }));

${recordBlockSource('  ')}

  function gatherRows(){
    return meta.questions.map((q,i)=>{
      const group=document.querySelector('[data-group="'+q.group+'"]');
      return {
        n:i+1,
        ord:'xx',
        id:'iran-'+topic+'-'+q.group,
        label:'Iran at War, Topic '+meta.n+', Filing '+(i+1),
        prompt:q.text,
        text:group?textValue(group).trim():'',
        confidence:''
      };
    });
  }

  function buildDocument(){
    const rows=gatherRows();
    const stamp=new Date();
    const dateline=UNIT.course+' · '+UNIT.unit+' · Topic '+meta.n;
    const head='<p><strong>'+esc(dateline)+'</strong></p><h2>'+esc(meta.title)+'</h2><p><em>Student work, copied '+esc(stamp.toLocaleString())+'</em></p><hr>';
    const bodyHtml=rows.map(r=>'<h3>'+esc(r.label)+'</h3><p><strong>Question: '+esc(r.prompt)+'</strong></p><p><strong>My response:</strong></p>'+bcParagraphsHtml(r.text,'em')).join('<hr>');
    const manifest=bcRecordManifest(rows,{topic:meta.key,expected:rows.length,isoStamp:stamp.toISOString()});
    const plain=[dateline,meta.title,'Student work, copied '+stamp.toLocaleString(),'']
      .concat(rows.map(r=>[r.label.toUpperCase(),'Question: '+r.prompt,'My response:',r.text,''].join('\\n')))
      .concat(manifest).join('\\n');
    return {html:head+bodyHtml+bcRecordFooterHtml(manifest),plain,count:rows.filter(r=>r.text).length,total:rows.length};
  }

  function say(message){
    const status=document.getElementById('iran-gather-status');
    if(status)status.textContent=message;
  }

  function selectOutput(out){
    try{
      const range=document.createRange();range.selectNodeContents(out);
      const sel=window.getSelection();sel.removeAllRanges();sel.addRange(range);return true;
    }catch(_){return false}
  }

  function gather(){
    const out=document.getElementById('iran-gather-output');
    if(!out)return null;
    const doc=buildDocument();
    out.innerHTML=doc.html;out.dataset.plain=doc.plain;
    const blank=doc.total-doc.count;
    say('Gathered '+doc.count+' of '+doc.total+' filings.'+(blank?' '+blank+' still blank. Complete '+(blank===1?'it':'them')+' and gather again.':' Copy this, then paste it into Canvas.'));
    return doc;
  }

  function copyFallback(out){
    let copied=false;try{copied=document.execCommand('copy')}catch(_){copied=false}
    if(copied){say('Copied with formatting. Paste it into Canvas.');return}
    if(navigator.clipboard&&navigator.clipboard.writeText){
      navigator.clipboard.writeText(out.dataset.plain||out.textContent||'')
        .then(()=>say('Copied as plain text. Paste it into Canvas.'))
        .catch(()=>say('Copy is blocked. Your work is selected; press Ctrl+C or Cmd+C.'));
    }else say('Your work is selected; press Ctrl+C or Cmd+C.');
  }

  function copy(){
    const out=document.getElementById('iran-gather-output');if(!out)return;
    if(!out.dataset.plain)gather();
    selectOutput(out);
    const html=out.innerHTML,plain=out.dataset.plain||'';
    if(window.ClipboardItem&&navigator.clipboard&&navigator.clipboard.write){
      navigator.clipboard.write([new ClipboardItem({'text/html':new Blob([html],{type:'text/html'}),'text/plain':new Blob([plain],{type:'text/plain'})})])
        .then(()=>say('Copied with formatting. Paste it into Canvas.'))
        .catch(()=>copyFallback(out));
    }else copyFallback(out);
  }

  function installGather(){
    if(document.getElementById('gather'))return;
    const section=document.createElement('section');
    section.className='ir-section';section.id='gather';
    section.innerHTML='<div class="ir-gather"><div class="ir-kicker red">Save your work</div><h2>Gather This Topic</h2><p>Your filings save only in this browser on this device. Gather them into one checked record, copy it, and paste it into the Canvas assignment.</p><div class="ir-gather-actions"><button class="ir-save" type="button" data-gather-topic>Gather This Topic</button><button class="ir-save secondary" type="button" data-copy-topic>Copy to Clipboard</button><button class="ir-clear" type="button" data-clear-topic>Clear This Topic</button><span class="ir-progress" data-topic-progress></span></div><p id="iran-gather-status" class="ir-status" role="status" aria-live="polite"></p><div id="iran-gather-output" class="ir-gather-output" tabindex="0" aria-label="Gathered work"><p class="ir-gather-placeholder">Gather your filings, copy them, then paste into Canvas.</p></div></div>';
    const sources=document.getElementById('sources');
    if(sources)sources.insertAdjacentElement('beforebegin',section);
    else document.querySelector('.ir-shell').appendChild(section);
    section.querySelector('[data-gather-topic]').addEventListener('click',gather);
    section.querySelector('[data-copy-topic]').addEventListener('click',copy);
    section.querySelector('[data-clear-topic]').addEventListener('click',()=>{
      if(!confirm('Clear the saved work for this Iran topic on this Chromebook?'))return;
      meta.questions.forEach(q=>{try{localStorage.removeItem(prefix+q.group)}catch(_){ }});
      location.reload();
    });
  }

  // Remote historical images degrade to a local, labelled fallback instead of
  // leaving a broken frame on a student page.
  document.querySelectorAll('.ir-map img[src^="http"]').forEach(img=>img.addEventListener('error',()=>{
    img.src=img.alt&&/map|strait|gulf/i.test(img.alt)?'../assets/images/week-art/map-fallback.svg':'../assets/images/week-art/card-fallback.svg';
    img.alt='Local fallback illustration; the remote historical image is unavailable.';
  },{once:true}));

  installGather();
  updateProgress();
})();
`;
}

function renderIranData(unit) {
  const total = (unit.topics || []).reduce((sum, topic) => sum + (topic.questions || []).length, 0);
  return `// GENERATED by scripts/build-iran.js. Do not hand-edit.\nwindow.BECURRENT_IRAN_PROGRESS=${JSON.stringify({
    total,
    prefix: 'bcv2-iran-topic-'
  })};\n`;
}

module.exports = { renderIranBrowser, renderIranData };
