#!/usr/bin/env node
'use strict';

/**
 * Write teacher/index.html, the BeCurrent Command Center: the teacher's front
 * door, the BeCurrent counterpart of BeHistorical's AP World Command Center.
 *
 *   node scripts/build-teacher-home.js            write
 *   node scripts/build-teacher-home.js --check    fail on drift, write nothing
 *
 * Two halves, both from sources rather than typing:
 *   - The lesson library is rendered here from scripts/lib/teaching-os.js, the
 *     same list teacher/teaching-os-manifest.js publishes, so the library and
 *     the JeffOS Teaching Command Center cannot point at different pages.
 *   - The Today card is filled in the browser from the live schedule
 *     (assets/data/announcements-schedule.js) and that manifest, because which
 *     lesson is "today" is a fact about the date the page is opened, not the date
 *     it was built.
 *
 * It replaces the hand-written Control Room page, which always featured Midterms
 * Topic 1 whatever the date.
 */

const fs = require('fs');
const path = require('path');
const { teachingTopics } = require('./lib/teaching-os');

const ROOT = path.resolve(__dirname, '..');
const CHECK = process.argv.includes('--check');
const OUT = path.join('teacher', 'index.html');
const G = '\x1b[32m', R = '\x1b[31m', X = '\x1b[0m';

const E = s => String(s == null ? '' : s).replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
const up = p => '../' + p;   // manifest paths are site-root relative; this page is in teacher/

// Units newest-first by the last date each appears on the schedule, so the unit
// being taught opens at the top of the library.
global.window = {};
require(path.join(ROOT, 'assets', 'data', 'announcements-schedule.js'));
const days = ((global.window.BECURRENT_SCHEDULE || {}).days) || [];
const lastSeen = {};
days.forEach(d => { if (d && d.topic && d.date && (!lastSeen[d.topic] || d.date > lastSeen[d.topic])) lastSeen[d.topic] = d.date; });

const topics = teachingTopics();
const units = [];
topics.forEach(t => {
  let u = units.find(x => x.unit === t.unit);
  if (!u) { u = { unit: t.unit, unitPage: t.unitPage, hub: t.hub, topics: [], last: '' }; units.push(u); }
  if (!u.hub && t.hub) u.hub = t.hub;
  u.topics.push(t);
  if ((lastSeen[t.code] || '') > u.last) u.last = lastSeen[t.code];
});
units.sort((a, b) => (b.last || '').localeCompare(a.last || '') || a.unit.localeCompare(b.unit));

const canvasDocs = fs.readdirSync(path.join(ROOT, 'docs', 'canvas'))
  .filter(f => /-calendar-events\.html$/.test(f)).sort();

const arrow = '→';
function row(t) {
  const links = [];
  if (t.teacher) links.push(`<a class="os-link" href="${E(up(t.teacher))}">Teaching OS ${arrow}</a>`);
  if (t.projector) links.push(`<a href="${E(up(t.projector))}" target="_blank" rel="noopener noreferrer">Projector ↗</a>`);
  links.push(`<a href="${E(up(t.student))}">Student page</a>`);
  return `<li class="lesson-row" data-code="${E(t.code)}"><span class="lesson-code">${E(t.topic)}</span><span class="lesson-title">${E(t.title)}</span><span class="lesson-links">${links.join('')}</span></li>`;
}
function unitBlock(u, i) {
  const n = u.topics.filter(t => t.teacher).length;
  const count = n ? `${n} Teaching OS ${n === 1 ? 'lesson' : 'lessons'}` : `${u.topics.length} student ${u.topics.length === 1 ? 'page' : 'pages'}`;
  const hub = u.hub ? `<a href="${E(up(u.hub))}">Unit Teaching OS ${arrow}</a>` : '';
  return `<details class="unit-block"${i === 0 ? ' open' : ''}><summary><span class="unit-name">${E(u.unit)}</span><span class="unit-count">${E(count)}</span></summary>
<ol class="lesson-list">${u.topics.map(row).join('')}</ol>
<p class="unit-links">${hub}<a href="${E(up(u.unitPage))}">Student unit page</a></p></details>`;
}

const html = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<meta name="description" content="BeCurrent Command Center: today's lesson from the live schedule, the Teaching OS library, and the daily classroom tools.">
<title>BeCurrent Command Center | Teacher</title>
<link rel="icon" href="../assets/favicon.svg" type="image/svg+xml">
<link rel="stylesheet" href="../assets/css/video-first.css?v=20261019r3">
<link rel="stylesheet" href="../assets/css/teacher-home.css?v=20261020">
</head>
<body class="teacher-home">
<!-- GENERATED by scripts/build-teacher-home.js. Do not hand-edit; rebuild. -->
<a class="skip" href="#main">Skip to teacher tools</a>
<header class="mast"><div class="mast-inner">
<a class="th-brand" href="../index.html" aria-label="BeCurrent home"><img src="../assets/images/brand/becurrent-wordmark-ink.svg" alt="BeCurrent" width="1786" height="266"></a>
<span class="th-label">Teacher Command Center</span>
<nav class="mast-nav" aria-label="Teacher navigation"><a href="../index.html">Website</a><a href="../announcements.html">TODAY board</a><a href="../daily/index.html">The Desk</a></nav>
</div></header>
<main id="main">
<section class="th-hero"><div class="th-hero-inner">
<div class="th-intro">
<p class="eyebrow">Current Events · Teacher operations</p>
<h1>BeCurrent <em>Command Center.</em></h1>
<p class="deck">Your single Current Events teaching hub. Open today's lesson first, then the Teaching OS library, the daily Desk, the TODAY board and the Canvas paste pages, without hunting through separate links.</p>
</div>
<aside class="today-card" aria-live="polite">
<p class="eyebrow" id="today-label">Today · Live schedule</p>
<h2 id="today-title">Checking today's schedule…</h2>
<p class="today-meta" id="today-meta"></p>
<div class="today-actions" id="today-actions"><a class="cta" href="${E(up(units[0] && units[0].hub || 'teacher/midterms.html'))}">Open the current unit's Teaching OS ${arrow}</a></div>
<p class="today-note" id="today-note"></p>
</aside>
</div></section>
<div class="wrap">
<section class="th-section" aria-labelledby="library-title">
<div class="th-section-head"><div><p class="eyebrow">Lesson library</p><h2 id="library-title">Teaching OS</h2></div><p>Today opens automatically above. Use the library when you need a different lesson.</p></div>
${units.map(unitBlock).join('\n')}
</section>
<section class="th-section" aria-labelledby="daily-title">
<div class="th-section-head"><div><p class="eyebrow">Every class</p><h2 id="daily-title">Daily routine</h2></div><p>Unit before lunch; CNN10 and the Desk after.</p></div>
<div class="tool-grid">
<a class="tool" href="../announcements.html" target="_blank" rel="noopener noreferrer"><span class="tool-kicker">Projector</span><strong>TODAY board</strong><span>Agenda, targets, success criteria, homework and what is coming next.</span></a>
<a class="tool" href="../daily/index.html"><span class="tool-kicker">After lunch</span><strong>The Desk</strong><span>The Lead, Your Pick and the two-week News Log students copy into Canvas.</span></a>
<a class="tool" href="../index.html"><span class="tool-kicker">Students</span><strong>Course website</strong><span>The front door students see: today's top story, briefing and investigations.</span></a>
</div>
</section>
<section class="th-section" aria-labelledby="canvas-title">
<div class="th-section-head"><div><p class="eyebrow">Teacher utility</p><h2 id="canvas-title">Canvas paste pages</h2></div><p>Generated from the same content as the site. Open beside Canvas and use the copy buttons.</p></div>
<div class="tool-grid">
${canvasDocs.map(f => {
    const key = f.replace(/-calendar-events\.html$/, '');
    const u = units.find(x => x.unitPage === `${key}/index.html`);
    return `<a class="tool" href="../docs/canvas/${E(f)}" target="_blank" rel="noopener noreferrer"><span class="tool-kicker">Calendar events</span><strong>${E(u ? u.unit : key)}</strong><span>Event tables with copy buttons; assignments are in the matching document in the repository.</span></a>`;
  }).join('\n')}
</div>
</section>
<p class="th-scope"><strong>Scope:</strong> a teacher launch surface, not access-controlled. GitHub Pages is public, so never type student names, grades or private records into any teacher page. Today reads the live schedule; the library and Today routing come from the same generated list, <code>teacher/teaching-os-manifest.js</code>, that the JeffOS Teaching Command Center reads.</p>
</div>
</main>
<footer class="footer">BeCurrent · Teacher Command Center · Generated by scripts/build-teacher-home.js</footer>
<script src="../assets/data/announcements-schedule.js"></script>
<script src="teaching-os-manifest.js"></script>
<script>
(function () {
  'use strict';
  var topics = (window.BECURRENT_TEACHING_OS && window.BECURRENT_TEACHING_OS.topics) || [];
  var days = ((window.BECURRENT_SCHEDULE || {}).days || []).filter(function (d) { return d && d.date; })
    .sort(function (a, b) { return a.date < b.date ? -1 : a.date > b.date ? 1 : 0; });
  function key(d) { return d.getFullYear() + '-' + String(d.getMonth() + 1).padStart(2, '0') + '-' + String(d.getDate()).padStart(2, '0'); }
  function nice(iso) { var p = iso.split('-').map(Number); return new Date(p[0], p[1] - 1, p[2]).toLocaleDateString('en-US', { weekday: 'long', month: 'long', day: 'numeric' }); }
  function hit(entry) { return topics.filter(function (t) { return t.code === (entry && entry.topic); })[0] || null; }
  function el(tag, cls, text, href) { var n = document.createElement(tag); if (cls) n.className = cls; if (text) n.textContent = text; if (href) n.href = href; return n; }
  var today = key(new Date());
  var entry = days.filter(function (d) { return d.date === today; })[0];
  var next = entry ? null : days.filter(function (d) { return d.date > today; })[0];
  var show = entry || next;
  var t = hit(show);
  var label = document.getElementById('today-label'), title = document.getElementById('today-title');
  var meta = document.getElementById('today-meta'), actions = document.getElementById('today-actions'), note = document.getElementById('today-note');
  if (!show) {
    title.textContent = 'No class on the schedule';
    note.textContent = 'Nothing scheduled today or ahead. Use the library below.';
    return;
  }
  label.textContent = entry ? 'Today · Live schedule' : 'Next class · ' + nice(show.date);
  title.textContent = (t && t.title) || show.topicTitle || show.topic || 'Scheduled class';
  meta.textContent = t ? t.unit + ' · ' + t.topic : (show.topicTitle || '');
  actions.textContent = '';
  if (t && t.teacher) actions.appendChild(el('a', 'cta', 'Open ' + t.topic + ' Teaching OS →', '../' + t.teacher));
  else if (t && t.hub) actions.appendChild(el('a', 'cta', 'Open the unit Teaching OS →', '../' + t.hub));
  if (t && t.projector) { var p = el('a', 'action-btn alt', 'Projector ↗', '../' + t.projector); p.target = '_blank'; p.rel = 'noopener noreferrer'; actions.appendChild(p); }
  if (t) actions.appendChild(el('a', 'action-btn alt', 'Student page', '../' + t.student));
  if (!t) actions.appendChild(el('a', 'cta', 'Open the TODAY board →', '../announcements.html'));
  note.textContent = show.note || '';
  if (t) {
    var row = document.querySelector('.lesson-row[data-code="' + t.code + '"]');
    if (row) { row.classList.add('is-today'); var block = row.closest('details'); if (block) block.open = true; }
  }
})();
</script>
</body>
</html>
`;

const full = path.join(ROOT, OUT);
const existing = fs.existsSync(full) ? fs.readFileSync(full, 'utf8') : null;
if (CHECK) {
  if (existing === html) { console.log(`${G}✓${X} The BeCurrent Command Center reproduces.`); process.exit(0); }
  console.error(`\n${R}${OUT} has drifted. Run: node scripts/build-teacher-home.js${X}\n`);
  process.exit(1);
}
if (existing === html) console.log(`${G}✓${X} Already up to date.`);
else { fs.writeFileSync(full, html, 'utf8'); console.log(`  wrote ${OUT}`); }
